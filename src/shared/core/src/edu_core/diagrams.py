"""Draw the diagram a question needs, from a spec the model fills in.

The model does not draw. Asked for an SVG or a set of coordinates it produces
something that looks like a ray diagram but is wrong, and a wrong diagram in an
exam question is worse than none at all. Instead it chooses one of a few kinds
below and supplies the values - a magnitude, an angle, a resistance - and the
code here draws it, correctly by construction.

Adding a kind means adding a spec and a renderer here, and naming it in the
prompt. Nothing else changes.

Rendered as PNG because that is what Google Forms will fetch and what the
browser and the PDF export both handle.
"""

import io
import math
from typing import Annotated, Literal

from pydantic import BaseModel, Field

# Drawn at twice the final size and shrunk back, which is the cheapest way to
# get smooth lines out of Pillow - it has no antialiasing of its own.
WIDTH, HEIGHT = 940, 620
SCALE = 2

GREEN = (31, 107, 74)
SOFT = (46, 139, 111)
INK = (34, 37, 31)
GREY = (116, 120, 117)
LINE = (199, 214, 206)
AMBER = (180, 126, 22)
WHITE = (255, 255, 255)

SERIES_COLOURS = [GREEN, AMBER, (56, 110, 170), (170, 60, 90)]
# Amber is kept for the resultant, so the vectors themselves never use it
ARROW_COLOURS = [GREEN, (56, 110, 170), (170, 60, 90), SOFT]

# The worker runs on a slim Debian image, which ships no fonts at all; the
# Dockerfile installs DejaVu. The Windows paths are for running this locally.
FONT_PATHS = (
    "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
    "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
    "C:/Windows/Fonts/segoeui.ttf",
    "C:/Windows/Fonts/segoeuib.ttf",
)


class DiagramError(RuntimeError):
    """The spec cannot be drawn."""


# --------------------------------------------------------------------- specs

class Vector(BaseModel):
    label: str = Field(..., description="Shown at the arrow tip, e.g. 'F₁ = 5 N'")
    magnitude: float = Field(..., gt=0, description="Length in the diagram's own units")
    angle_degrees: float = Field(
        ..., description="Anticlockwise from the positive x-axis"
    )


class VectorsSpec(BaseModel):
    """Vectors drawn from one origin. For addition, resolution and components."""

    kind: Literal["vectors"]
    caption: str = ""
    vectors: list[Vector] = Field(..., min_length=1, max_length=4)
    show_resultant: bool = Field(
        False, description="Also draw the vector sum, dashed and labelled R"
    )


class Force(BaseModel):
    label: str = Field(..., description="Shown at the arrow tip, e.g. 'W = mg'")
    direction_degrees: float = Field(
        ..., description="Anticlockwise from the positive x-axis; 90 is up"
    )
    relative_length: float = Field(1.0, gt=0, le=2.0)


class FreeBodySpec(BaseModel):
    """A body with the forces acting on it."""

    kind: Literal["free_body"]
    caption: str = ""
    body_label: str = ""
    forces: list[Force] = Field(..., min_length=1, max_length=6)


class Point(BaseModel):
    x: float
    y: float


class Series(BaseModel):
    label: str = ""
    points: list[Point] = Field(..., min_length=2)


class GraphSpec(BaseModel):
    """A plotted graph. For motion graphs, characteristics and functions."""

    kind: Literal["graph"]
    caption: str = ""
    x_label: str = "x"
    y_label: str = "y"
    series: list[Series] = Field(..., min_length=1, max_length=4)


class Component(BaseModel):
    label: str = Field(..., description="e.g. 'R₁ = 4 Ω'")


class CircuitSpec(BaseModel):
    """A single-loop circuit with resistors in series or in parallel."""

    kind: Literal["circuit"]
    caption: str = ""
    source_label: str = Field("12 V", description="The cell or battery")
    arrangement: Literal["series", "parallel"]
    components: list[Component] = Field(..., min_length=1, max_length=4)


class Substituent(BaseModel):
    position: int = Field(..., ge=1, le=8, description="Which ring vertex, from 1")
    label: str = Field(..., description="The group, e.g. OH, CH3, Cl, NO2")


class StructureSpec(BaseModel):
    """A ring skeletal formula: benzene and the rings built on it.

    Covers what FSc chemistry asks most - benzene, phenol, toluene,
    chlorobenzene, cyclohexane - exactly, because a ring is geometry. It is not
    a general structure editor: chains and fused rings are out of its reach.
    """

    kind: Literal["structure"]
    caption: str = ""
    ring_size: int = Field(6, ge=3, le=8)
    aromatic: bool = Field(
        False, description="Draw the inner circle, as in benzene"
    )
    kekule: bool = Field(
        False, description="Draw alternating double bonds instead of the circle"
    )
    substituents: list[Substituent] = Field(default_factory=list, max_length=6)


class IllustrationSpec(BaseModel):
    """A picture of a situation, generated by Imagen rather than drawn.

    For scenes that set a question up and carry no measurement: a trolley on a
    slope, a beaker over a flame. Never for anything exact - an image model
    cannot spell, so it would label a circuit with letters that spell nothing.
    """

    kind: Literal["illustration"]
    caption: str = ""
    prompt: str = Field(
        ...,
        min_length=8,
        description=(
            "What the picture shows, as a plain scene: 'a wooden block resting "
            "on a ramp, side view'. No labels, arrows, values or units - those "
            "cannot be drawn correctly and are left out."
        ),
    )


DiagramSpec = Annotated[
    VectorsSpec | FreeBodySpec | GraphSpec | CircuitSpec | StructureSpec
    | IllustrationSpec,
    Field(discriminator="kind"),
]


# ------------------------------------------------------------------ drawing

def _fonts():
    from PIL import ImageFont

    regular = bold = None
    for path in FONT_PATHS:
        try:
            font = ImageFont.truetype(path, 11 * SCALE)
        except OSError:
            continue
        if "Bold" in path or "segoeuib" in path:
            bold = bold or path
        else:
            regular = regular or path
    if regular is None:
        raise DiagramError(
            "No usable font found. The worker image installs fonts-dejavu-core; "
            "locally it falls back to Segoe UI."
        )

    def at(size: int, heavy: bool = False):
        return ImageFont.truetype(bold if heavy and bold else regular, size * SCALE)

    return at


class Canvas:
    """A drawing surface in final-size coordinates; it scales up internally."""

    def __init__(self, caption: str = ""):
        from PIL import Image, ImageDraw

        self.image = Image.new("RGB", (WIDTH * SCALE, HEIGHT * SCALE), WHITE)
        self.draw = ImageDraw.Draw(self.image)
        self.font = _fonts()
        self.caption = caption

    # -- primitives, all taking final-size coordinates ----------------------

    def line(self, x0, y0, x1, y1, colour=INK, width=1.6, dash=0.0):
        if dash:
            length = math.hypot(x1 - x0, y1 - y0)
            if length == 0:
                return
            steps = max(1, int(length / dash))
            for i in range(steps):
                if i % 2:
                    continue
                a, b = i / steps, min(1.0, (i + 1) / steps)
                self.line(x0 + (x1 - x0) * a, y0 + (y1 - y0) * a,
                          x0 + (x1 - x0) * b, y0 + (y1 - y0) * b,
                          colour, width)
            return
        self.draw.line(
            [(x0 * SCALE, y0 * SCALE), (x1 * SCALE, y1 * SCALE)],
            fill=colour, width=max(1, int(width * SCALE)),
        )

    def arrow(self, x0, y0, x1, y1, colour=GREEN, width=2.0, head=11.0, dash=0.0):
        self.line(x0, y0, x1, y1, colour, width, dash)
        angle = math.atan2(y1 - y0, x1 - x0)
        points = [(x1, y1)]
        for turn in (2.5, -2.5):
            points.append((x1 + head * math.cos(angle + turn),
                           y1 + head * math.sin(angle + turn)))
        self.draw.polygon([(x * SCALE, y * SCALE) for x, y in points], fill=colour)

    def rect(self, x0, y0, x1, y1, outline=INK, fill=None, width=1.6):
        self.draw.rectangle(
            [(x0 * SCALE, y0 * SCALE), (x1 * SCALE, y1 * SCALE)],
            outline=outline, fill=fill, width=max(1, int(width * SCALE)),
        )

    def text(self, x, y, body, size=11, colour=INK, heavy=False,
             anchor="lt", plate=False):
        font = self.font(size, heavy)
        if plate:
            box = self.draw.textbbox((x * SCALE, y * SCALE), body, font=font,
                                     anchor=anchor)
            pad = 3 * SCALE
            self.draw.rectangle(
                [box[0] - pad, box[1] - pad, box[2] + pad, box[3] + pad], fill=WHITE
            )
        self.draw.text((x * SCALE, y * SCALE), body, font=font, fill=colour,
                       anchor=anchor)

    def finish(self) -> bytes:
        from PIL import Image

        if self.caption:
            self.text(WIDTH / 2, HEIGHT - 26, self.caption, size=11,
                      colour=GREY, anchor="mt")
        small = self.image.resize((WIDTH, HEIGHT), Image.LANCZOS)
        buffer = io.BytesIO()
        small.save(buffer, format="PNG", optimize=True)
        return buffer.getvalue()


def _label_clear(canvas, tx, ty, dx, dy, body, colour, gap=15.0):
    """Place a label beyond the arrow tip, on the side the arrow points.

    Putting it on top of the tip and hiding the overlap behind a white plate
    leaves a sliver of arrowhead sticking out, which looks like a typo.
    """
    if abs(dx) >= abs(dy):
        x = tx + gap if dx >= 0 else tx - gap
        y, anchor = ty, ("lm" if dx >= 0 else "rm")
    else:
        y = ty - gap if dy > 0 else ty + gap
        x, anchor = tx, ("mb" if dy > 0 else "mt")
    canvas.text(x, y, body, size=12, colour=colour, heavy=True, anchor=anchor)


def _nice_axis(low: float, high: float, ticks: int = 4):
    """Round the range outwards to a step a human would have chosen."""
    span = (high - low) or 1.0
    raw = span / ticks
    magnitude = 10 ** math.floor(math.log10(raw)) if raw > 0 else 1.0
    for factor in (1, 2, 2.5, 5, 10):
        if raw <= factor * magnitude:
            step = factor * magnitude
            break
    else:                                     # pragma: no cover - unreachable
        step = 10 * magnitude
    return math.floor(low / step) * step, math.ceil(high / step) * step, step


# ----------------------------------------------------------------- renderers

def _draw_vectors(spec: VectorsSpec) -> bytes:
    canvas = Canvas(spec.caption)
    ox, oy = WIDTH / 2, HEIGHT / 2 + 20

    arrows = [(v.label, v.magnitude * math.cos(math.radians(v.angle_degrees)),
               v.magnitude * math.sin(math.radians(v.angle_degrees)))
              for v in spec.vectors]
    if spec.show_resultant:
        arrows.append(("R", sum(a[1] for a in arrows), sum(a[2] for a in arrows)))

    longest = max(math.hypot(dx, dy) for _, dx, dy in arrows) or 1.0
    unit = min(WIDTH * 0.36, HEIGHT * 0.42) / longest

    # Axes through the origin, so the angles can be read
    canvas.line(ox - WIDTH * 0.42, oy, ox + WIDTH * 0.42, oy, LINE, 1.2)
    canvas.line(ox, oy - HEIGHT * 0.38, ox, oy + HEIGHT * 0.30, LINE, 1.2)

    for index, (label, dx, dy) in enumerate(arrows):
        resultant = spec.show_resultant and index == len(arrows) - 1
        colour = AMBER if resultant else ARROW_COLOURS[index % len(ARROW_COLOURS)]
        tx, ty = ox + dx * unit, oy - dy * unit     # screen y grows downward
        canvas.arrow(ox, oy, tx, ty, colour, width=2.2,
                     dash=7.0 if resultant else 0.0)
        _label_clear(canvas, tx, ty, dx, dy, label, colour)

    canvas.text(ox + 6, oy + 6, "O", size=10, colour=GREY)
    return canvas.finish()


def _draw_free_body(spec: FreeBodySpec) -> bytes:
    canvas = Canvas(spec.caption)
    cx, cy = WIDTH / 2, HEIGHT / 2 + 10
    half = 44

    canvas.rect(cx - half, cy - half, cx + half, cy + half,
                outline=GREEN, fill=(231, 241, 235), width=2.0)
    if spec.body_label:
        canvas.text(cx, cy, spec.body_label, size=13, colour=GREEN, heavy=True,
                    anchor="mm")

    longest = max(f.relative_length for f in spec.forces) or 1.0
    reach = min(WIDTH * 0.26, HEIGHT * 0.30)

    for index, force in enumerate(spec.forces):
        angle = math.radians(force.direction_degrees)
        length = reach * (force.relative_length / longest)
        # Start exactly on the square's edge, so no stub shows inside the body
        edge = half / max(abs(math.cos(angle)), abs(math.sin(angle)))
        sx = cx + edge * math.cos(angle)
        sy = cy - edge * math.sin(angle)
        tx = cx + (edge + length) * math.cos(angle)
        ty = cy - (edge + length) * math.sin(angle)
        colour = ARROW_COLOURS[index % len(ARROW_COLOURS)]
        canvas.arrow(sx, sy, tx, ty, colour, width=2.2)
        _label_clear(canvas, tx, ty, math.cos(angle), math.sin(angle),
                     force.label, colour)

    return canvas.finish()


def _draw_graph(spec: GraphSpec) -> bytes:
    canvas = Canvas(spec.caption)
    left, right = 92.0, WIDTH - 52.0
    top, bottom = 54.0, HEIGHT - 86.0

    xs = [p.x for s in spec.series for p in s.points]
    ys = [p.y for s in spec.series for p in s.points]
    # Include the origin when the data sits near it, so a slope reads honestly,
    # then round the range outwards so the ticks are numbers a person would pick
    x0, x1, x_step = _nice_axis(min(min(xs), 0.0), max(xs))
    y0, y1, y_step = _nice_axis(min(min(ys), 0.0), max(ys))

    def place(px, py):
        return (left + (px - x0) / (x1 - x0) * (right - left),
                bottom - (py - y0) / (y1 - y0) * (bottom - top))

    steps_x = max(1, round((x1 - x0) / x_step))
    steps_y = max(1, round((y1 - y0) / y_step))
    for step in range(steps_y + 1):
        value = y0 + step * y_step
        gy = bottom - (value - y0) / (y1 - y0) * (bottom - top)
        canvas.line(left, gy, right, gy, LINE, 0.9)
        canvas.text(left - 10, gy, f"{value:g}", size=10, colour=GREY, anchor="rm")
    for step in range(steps_x + 1):
        value = x0 + step * x_step
        gx = left + (value - x0) / (x1 - x0) * (right - left)
        canvas.line(gx, top, gx, bottom, LINE, 0.9)
        canvas.text(gx, bottom + 10, f"{value:g}", size=10, colour=GREY, anchor="mt")

    canvas.line(left, top, left, bottom, INK, 1.8)
    canvas.line(left, bottom, right, bottom, INK, 1.8)

    for index, series in enumerate(spec.series):
        colour = SERIES_COLOURS[index % len(SERIES_COLOURS)]
        placed = [place(p.x, p.y) for p in series.points]
        for (ax, ay), (bx, by) in zip(placed, placed[1:]):
            canvas.line(ax, ay, bx, by, colour, 2.4)
        for px, py in placed:
            canvas.draw.ellipse(
                [((px - 3.2) * SCALE, (py - 3.2) * SCALE),
                 ((px + 3.2) * SCALE, (py + 3.2) * SCALE)], fill=colour)
        if series.label:
            lx, ly = placed[-1]
            # Flip the label inwards when the last point sits against the frame,
            # otherwise it is drawn off the edge of the image
            inside = lx < right - 70
            canvas.text(lx + (10 if inside else -10), ly - 12, series.label,
                        size=11, colour=colour, heavy=True,
                        anchor="lm" if inside else "rm", plate=True)

    canvas.text((left + right) / 2, bottom + 34, spec.x_label, size=12,
                colour=INK, heavy=True, anchor="mt")
    canvas.text(left, top - 18, spec.y_label, size=12, colour=INK,
                heavy=True, anchor="lb")
    return canvas.finish()


def _draw_circuit(spec: CircuitSpec) -> bytes:
    canvas = Canvas(spec.caption)
    left, right = 150.0, WIDTH - 150.0
    top, bottom = 190.0, HEIGHT - 230.0
    mid_y = (top + bottom) / 2

    def cell(x: float, y: float) -> None:
        """A cell across a vertical wire: one long plate, one short.

        The wire has to be broken for it, not drawn over - otherwise the long
        plate lands on the wire and only the short one is visible.
        """
        canvas.line(x, top, x, y - 11, INK, 1.8)
        canvas.line(x, y + 11, x, bottom, INK, 1.8)
        canvas.line(x - 17, y - 11, x + 17, y - 11, INK, 2.6)   # long  (+)
        canvas.line(x - 9, y + 11, x + 9, y + 11, INK, 1.8)     # short (-)
        canvas.text(x - 26, y, spec.source_label, size=12, colour=INK,
                    heavy=True, anchor="rm")

    def resistor(x0: float, x1: float, y: float, label: str) -> None:
        canvas.line(x0 - 1, y, x0, y, INK, 1.8)
        canvas.rect(x0, y - 13, x1, y + 13, outline=INK, fill=WHITE, width=1.8)
        canvas.text((x0 + x1) / 2, y - 22, label, size=12, colour=GREEN,
                    heavy=True, anchor="mb")

    if spec.arrangement == "series":
        canvas.line(left, top, right, top, INK, 1.8)
        canvas.line(left, bottom, right, bottom, INK, 1.8)
        canvas.line(right, top, right, bottom, INK, 1.8)
        cell(left, mid_y)

        span = (right - left) / len(spec.components)
        for index, component in enumerate(spec.components):
            centre = left + span * (index + 0.5)
            box = min(76.0, span * 0.6)
            resistor(centre - box / 2, centre + box / 2, top, component.label)
    else:
        cell(left, mid_y)

        # Two nodes, one per side of the branches. The left node must touch only
        # the top wire and the right node only the bottom wire - joining both to
        # the top rail would short the branches out.
        node_a, node_b = left + 150, right - 70
        count = len(spec.components)
        rows = [top + (bottom - top) * (i + 1) / (count + 1) for i in range(count)]

        canvas.line(left, top, node_a, top, INK, 1.8)
        canvas.line(node_a, top, node_a, rows[-1], INK, 1.8)
        canvas.line(node_b, rows[0], node_b, bottom, INK, 1.8)
        canvas.line(left, bottom, node_b, bottom, INK, 1.8)

        for component, y in zip(spec.components, rows):
            canvas.line(node_a, y, node_b, y, INK, 1.8)
            centre = (node_a + node_b) / 2
            resistor(centre - 42, centre + 42, y, component.label)

    return canvas.finish()


def _draw_structure(spec: StructureSpec) -> bytes:
    canvas = Canvas(spec.caption)
    cx, cy = WIDTH / 2, HEIGHT / 2 + 6
    radius = 118.0
    n = spec.ring_size

    # Vertex 1 at the top, going clockwise, which is how these are drawn in books
    def vertex(i: int) -> tuple[float, float]:
        angle = -math.pi / 2 + 2 * math.pi * i / n
        return cx + radius * math.cos(angle), cy + radius * math.sin(angle)

    points = [vertex(i) for i in range(n)]
    for i, (x0, y0) in enumerate(points):
        x1, y1 = points[(i + 1) % n]
        canvas.line(x0, y0, x1, y1, INK, 2.4)

    if spec.aromatic and not spec.kekule:
        inner = radius * 0.58
        canvas.draw.ellipse(
            [((cx - inner) * SCALE, (cy - inner) * SCALE),
             ((cx + inner) * SCALE, (cy + inner) * SCALE)],
            outline=INK, width=max(1, int(2.2 * SCALE)))
    elif spec.kekule:
        # A second, shorter line inside every other bond
        for i in range(0, n - n % 2, 2):
            x0, y0 = points[i]
            x1, y1 = points[(i + 1) % n]
            mx, my = (x0 + x1) / 2, (y0 + y1) / 2
            tx, ty = (cx - mx), (cy - my)
            length = math.hypot(tx, ty) or 1.0
            ox, oy = tx / length * 13, ty / length * 13
            canvas.line(x0 * 0.82 + x1 * 0.18 + ox, y0 * 0.82 + y1 * 0.18 + oy,
                        x0 * 0.18 + x1 * 0.82 + ox, y0 * 0.18 + y1 * 0.82 + oy,
                        INK, 2.2)

    for item in spec.substituents:
        index = (item.position - 1) % n
        vx, vy = points[index]
        angle = math.atan2(vy - cy, vx - cx)
        bx, by = vx + 26 * math.cos(angle), vy + 26 * math.sin(angle)
        canvas.line(vx, vy, bx, by, INK, 2.2)
        canvas.text(bx + 12 * math.cos(angle), by + 12 * math.sin(angle),
                    item.label, size=14, colour=GREEN, heavy=True, anchor="mm")

    return canvas.finish()


def _draw_illustration(spec: IllustrationSpec) -> bytes:
    """Ask Vertex for the picture, then frame it like the drawn ones."""
    from PIL import Image

    from edu_core.image_gen import ImageGenerationError, generate

    try:
        raw = generate(spec.prompt)
    except ImageGenerationError as error:
        raise DiagramError(str(error)) from error

    picture = Image.open(io.BytesIO(raw)).convert("RGB")
    canvas = Canvas(spec.caption)

    # Fit inside the usual frame, leaving the caption its strip at the bottom
    room_w, room_h = (WIDTH - 60) * SCALE, (HEIGHT - 90) * SCALE
    ratio = min(room_w / picture.width, room_h / picture.height)
    fitted = picture.resize(
        (max(1, int(picture.width * ratio)), max(1, int(picture.height * ratio))),
        Image.LANCZOS,
    )
    canvas.image.paste(
        fitted,
        ((WIDTH * SCALE - fitted.width) // 2, int(24 * SCALE)),
    )
    return canvas.finish()


RENDERERS = {
    "vectors": _draw_vectors,
    "free_body": _draw_free_body,
    "graph": _draw_graph,
    "circuit": _draw_circuit,
    "structure": _draw_structure,
    "illustration": _draw_illustration,
}


def render(spec: DiagramSpec) -> bytes:
    """Draw the spec and return a PNG."""
    renderer = RENDERERS.get(spec.kind)
    if renderer is None:                      # pragma: no cover - guarded by the type
        raise DiagramError(f"No renderer for {spec.kind!r}")
    try:
        return renderer(spec)
    except DiagramError:
        raise
    except Exception as error:
        raise DiagramError(f"Could not draw the {spec.kind} diagram: {error}") from error


def alt_text(spec: DiagramSpec) -> str:
    """A description for screen readers and for the Google Form's altText."""
    if spec.caption:
        return spec.caption
    if spec.kind == "illustration":
        return spec.prompt[:400]
    return {
        "vectors": "Vector diagram",
        "free_body": "Free-body diagram",
        "graph": "Graph",
        "circuit": "Circuit diagram",
        "structure": "Chemical structure",
    }[spec.kind]


def store(storage, project_id: str, question_id: str, spec: DiagramSpec) -> tuple[str, str]:
    """Draw the spec, put the PNG in object storage and return (path, alt text).

    The storage client is passed in rather than built here, so this module stays
    pure drawing and can be tested without a bucket.
    """
    path = diagram_path(project_id, question_id)
    storage.upload(path, render(spec), content_type="image/png")
    return path, alt_text(spec)


def diagram_path(project_id: str, question_id: str) -> str:
    """Where a question's diagram lives in the bucket."""
    return f"{project_id}/diagrams/{question_id}.png"
