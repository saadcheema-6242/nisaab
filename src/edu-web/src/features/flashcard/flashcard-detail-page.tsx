import { Result, useAtomRefresh, useAtomValue } from '@effect-atom/atom-react'
import { FlashcardDetail } from './components/flashcard-detail'
import { FlashcardHeader } from './components/flashcard-header'
import { GeneratingPlaceholder } from '@/components/generating-placeholder'
import { flashcardsAtom } from '@/data-acess/flashcard'
import { usePollWhile } from '@/hooks/use-poll-while'

type FlashcardDetailPageProps = {
  flashcardGroupId: string
  projectId: string
}

export const FlashcardDetailPage = ({
  flashcardGroupId,
  projectId,
}: FlashcardDetailPageProps) => {
  const cardsAtom = flashcardsAtom(`${projectId}:${flashcardGroupId}`)
  const cardsResult = useAtomValue(cardsAtom)
  const refreshCards = useAtomRefresh(cardsAtom)

  // Flashcards are generated by the worker; keep checking until they arrive
  const isEmpty =
    Result.isSuccess(cardsResult) && cardsResult.value.length === 0
  const timedOut = usePollWhile(isEmpty, refreshCards)

  return (
    <div className="flex h-full flex-col">
      <FlashcardHeader
        flashcardGroupId={flashcardGroupId}
        projectId={projectId}
      />

      <div className="flex flex-1 flex-col min-h-0 overflow-hidden">
        <div className="max-w-5xl mx-auto w-full flex flex-col flex-1 min-h-0">
          {isEmpty ? (
            <GeneratingPlaceholder what="flashcards" timedOut={timedOut} />
          ) : (
            <FlashcardDetail
              flashcardGroupId={flashcardGroupId}
              className="flex-1"
            />
          )}
        </div>
      </div>
    </div>
  )
}
